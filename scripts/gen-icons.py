#!/usr/bin/env python3
"""Generate Nano Agent's launcher, themed and status-bar icons for android/.

The mark: a hexagonal "nano cell" ring with a bright core and one orbiting spark, in the
violet -> cyan Nano Agent gradient on a deep-night tile. Idempotent; re-run after brand.py.

Writes (res/ of the app):
  drawable/ic_launcher_foreground_nm.xml       gradient mark, 108dp adaptive canvas
  drawable/ic_launcher_foreground_nm_dark.xml  white mark (the "dark" icon skin)
  drawable/ic_launcher_monochrome.xml          flat mark for Android 13+ themed icons
  drawable/ic_stat_nanomuse.xml                24dp flat mark for notifications
  values*/ic_launcher_background.xml, values/ic_launcher_alt_colors.xml
  mipmap-*/ic_launcher*.png                    legacy rasters (Pillow)

    python3 scripts/gen-icons.py
"""

from __future__ import annotations

import math
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android" / "src" / "android" / "app" / "src" / "main" / "res"

VIOLET = "#6C3CF0"
CYAN = "#17C3E6"
NIGHT = "#120B24"
WHITE = "#FFFFFF"

# Geometry in the 108-unit adaptive canvas (the visible safe zone is the 66-unit circle).
C = 54.0
R_OUT = 25.0     # hexagon ring, outer radius
R_IN = 18.5      # hexagon ring, inner radius
R_CORE = 7.0     # the core
SPARK = (C + 22.5 * math.cos(math.radians(-38)), C + 22.5 * math.sin(math.radians(-38)))
R_SPARK = 4.6
R_SPARK_GAP = 7.4  # the ring is cut around the spark


def hexagon(r: float, cx: float = C, cy: float = C) -> list[tuple[float, float]]:
    return [(cx + r * math.cos(math.radians(60 * i - 90)), cy + r * math.sin(math.radians(60 * i - 90))) for i in range(6)]


def circle_path(cx: float, cy: float, r: float) -> str:
    return (f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0"
            f"a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0Z")


def poly_path(pts: list[tuple[float, float]]) -> str:
    return "M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z"


def scale(pts, s, ox=0.0, oy=0.0):
    return [(ox + x * s, oy + y * s) for x, y in pts]


def mark_paths(s: float = 1.0, o: float = 0.0) -> tuple[str, str, str, str]:
    """(ring outer, ring inner, core, spark-gap circle, spark) as path data; evenOdd fill."""
    outer = poly_path(scale(hexagon(R_OUT), s, o, o))
    inner = poly_path(scale(hexagon(R_IN), s, o, o))
    core = circle_path(o + C * s, o + C * s, R_CORE * s)
    spark = circle_path(o + SPARK[0] * s, o + SPARK[1] * s, R_SPARK * s)
    return outer, inner, core, spark


def gap_path(s: float = 1.0, o: float = 0.0) -> str:
    return circle_path(o + SPARK[0] * s, o + SPARK[1] * s, R_SPARK_GAP * s)


HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          "<!-- Nano Agent: generated by scripts/gen-icons.py; do not edit by hand. -->\n")


def vector(size_dp: int, viewport: float, body: str) -> str:
    return (HEADER +
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
            f'    android:viewportWidth="{viewport:g}" android:viewportHeight="{viewport:g}">\n'
            f"{body}</vector>\n")


def mark_body(fill: str, s: float = 1.0, o: float = 0.0, gradient: bool = False) -> str:
    outer, inner, core, spark = mark_paths(s, o)
    gap = gap_path(s, o)
    # The ring with the spark's gap punched out is drawn as a clip-path group.
    if gradient:
        lo, hi = o + (C - R_OUT) * s, o + (C + R_OUT) * s
        paint = ("\n        <aapt:attr name=\"android:fillColor\">\n"
                 f"            <gradient android:type=\"linear\" android:startX=\"{lo:.2f}\" android:startY=\"{hi:.2f}\"\n"
                 f"                android:endX=\"{hi:.2f}\" android:endY=\"{lo:.2f}\">\n"
                 f"                <item android:offset=\"0\" android:color=\"#FF{VIOLET[1:]}\" />\n"
                 f"                <item android:offset=\"1\" android:color=\"#FF{CYAN[1:]}\" />\n"
                 "            </gradient>\n        </aapt:attr>\n    ")
        open_tag = lambda d: f'    <path android:fillType="evenOdd" android:pathData="{d}">{paint}</path>\n'
    else:
        open_tag = lambda d: f'    <path android:fillType="evenOdd" android:pathData="{d}" android:fillColor="{fill}" />\n'
    # clip: everything except the gap circle (evenOdd of the canvas square + gap)
    lo_c, hi_c = o, o + 108 * s
    canvas = f"M{lo_c:.2f},{lo_c:.2f}H{hi_c:.2f}V{hi_c:.2f}H{lo_c:.2f}Z"
    return ("    <group>\n"
            f'        <clip-path android:fillType="evenOdd" android:pathData="{canvas}{gap}" />\n'
            + "    " + open_tag(outer + inner) +
            "    </group>\n"
            + open_tag(core) + open_tag(spark))


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def vectors() -> None:
    d = RES / "drawable"
    write(d / "ic_launcher_foreground_nm.xml", vector(108, 108, mark_body("", gradient=True)))
    write(d / "ic_launcher_foreground_nm_dark.xml", vector(108, 108, mark_body("#FFFFFFFF")))
    write(d / "ic_launcher_monochrome.xml", vector(108, 108, mark_body("#FFFFFFFF")))
    # 24dp status-bar mark: the 108 canvas's 72-unit visible area scaled into 24 units.
    s = 24 / 60.0
    o = -(C - 30) * s
    write(d / "ic_stat_nanomuse.xml", vector(24, 24, mark_body("#FFFFFFFF", s, o)))


def colors() -> None:
    bg = HEADER.replace("<!--", "<!--", 1) + "<resources>\n    <color name=\"ic_launcher_background\">{}</color>\n</resources>\n"
    write(RES / "values" / "ic_launcher_background.xml", bg.format(NIGHT))
    write(RES / "values-night" / "ic_launcher_background.xml", bg.format(NIGHT))
    write(RES / "values" / "ic_launcher_alt_colors.xml", HEADER +
          "<resources>\n"
          "    <!-- Forced-mode alternate icons (Settings > Appearance > App icon). -->\n"
          f"    <color name=\"ic_launcher_bg_force_light\">{WHITE}</color>\n"
          f"    <color name=\"ic_launcher_bg_force_dark\">{NIGHT}</color>\n"
          "</resources>\n")


# --- rasters ---------------------------------------------------------------------------------

SS = 4  # supersampling


def hex_rgb(h: str) -> tuple[int, int, int]:
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def mark_mask(px: int) -> Image.Image:
    big = px * SS
    k = big / 108.0
    m = Image.new("L", (big, big), 0)
    dr = ImageDraw.Draw(m)
    dr.polygon([(x * k, y * k) for x, y in hexagon(R_OUT)], fill=255)
    dr.polygon([(x * k, y * k) for x, y in hexagon(R_IN)], fill=0)
    gx, gy = SPARK
    dr.ellipse([(gx - R_SPARK_GAP) * k, (gy - R_SPARK_GAP) * k, (gx + R_SPARK_GAP) * k, (gy + R_SPARK_GAP) * k], fill=0)
    dr.ellipse([(C - R_CORE) * k, (C - R_CORE) * k, (C + R_CORE) * k, (C + R_CORE) * k], fill=255)
    dr.ellipse([(gx - R_SPARK) * k, (gy - R_SPARK) * k, (gx + R_SPARK) * k, (gy + R_SPARK) * k], fill=255)
    return m.resize((px, px), Image.LANCZOS)


def gradient(px: int) -> Image.Image:
    a, b = hex_rgb(VIOLET), hex_rgb(CYAN)
    g = Image.new("RGB", (px, px))
    pix = g.load()
    for y in range(px):
        for x in range(px):
            t = min(1.0, max(0.0, ((x / px) + (1 - y / px)) / 2 * 1.6 - 0.3))
            pix[x, y] = tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))
    return g


def foreground(px: int, white: bool) -> Image.Image:
    mask = mark_mask(px)
    fill = Image.new("RGB", (px, px), hex_rgb(WHITE)) if white else gradient(px)
    out = Image.new("RGBA", (px, px), (0, 0, 0, 0))
    out.paste(fill, (0, 0), mask)
    return out


def legacy(px: int) -> Image.Image:
    """Full icon: night tile (rounded square) with the mark, as pre-adaptive launchers show it."""
    big = px * SS
    tile = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    ImageDraw.Draw(tile).rounded_rectangle([0, 0, big - 1, big - 1], radius=big * 0.22, fill=hex_rgb(NIGHT) + (255,))
    tile = tile.resize((px, px), Image.LANCZOS)
    # The mark's 108 canvas is 1.5x the visible 72; crop the middle.
    fg = foreground(round(px * 1.5), white=False)
    off = (fg.width - px) // 2
    tile.alpha_composite(fg.crop((off, off, off + px, off + px)))
    return tile


def rasters() -> None:
    for d in sorted(RES.glob("mipmap-*dpi")):
        for f in sorted(d.glob("*.png")):
            w = Image.open(f).size[0]
            if f.name == "ic_launcher.png":
                img = legacy(w)
            elif f.name == "ic_launcher_foreground_dark.png":
                img = foreground(w, white=True)
            else:
                img = foreground(w, white=False)
            img.save(f, optimize=True)


if __name__ == "__main__":
    vectors()
    colors()
    rasters()
    print("icons written")
